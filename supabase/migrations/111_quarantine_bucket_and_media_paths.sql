-- 111 · 下架的文件要**移走**，不是删掉
--
-- ─── 问题 ───────────────────────────────────────────────────────────────
--
-- 迁移 110 的墓碑只换掉了数据库里的内容。**文件还躺在原来的桶里。**
-- 读了存储策略之后暴露面很具体：
--
--   chat-media 的 SELECT 策略是按会话文件夹判的 ——
--   **只要还是那个会话的成员，知道路径就能一直签出 URL。**
--   墓碑把 attachments 清空只是让客户端不知道路径了，上传者自己当然知道。
--
--   roam-media 的策略里有 EXISTS(travel_posts WHERE image_url = name)，
--   所以下架把 image_url 置空之后外人自动读不到了 ——
--   但**上传者本人仍然读得到**（策略第一个分支是 foldername[1] = auth.uid()）。
--
-- ─── 为什么不是「删掉」───────────────────────────────────────────────────
--
-- 18 U.S.C. §2258A(h)：CSAM 材料上报后要**保存一年**，(h)(3) 还要求
-- "maintained in a secure location and access to the material shall be
-- limited"。**删掉等于毁灭我们有义务保存的证据。**
--
-- 所以是「移到用户够不到的地方」而不是「销毁」：
-- quarantine 桶 private + **零策略** = 只有 service_role 碰得到。
-- 一次搬运同时满足两件事：用户够不到 · 我们留着。
--
-- 完整定义以线上为准（apply_migration 已应用）。
